/**
 * Render Kotlin source from the shared TypeScript packages.
 *
 * The family app's words and colours are defined once, in `frontend/packages`,
 * and the web apps read them directly. The Android app cannot import
 * TypeScript, so these functions write the same values out as Kotlin. A test in
 * `frontend/packages/i18n` fails if the committed Kotlin goes stale, so the two
 * cannot drift apart.
 */

const HEADER = (source) =>
  `// Generated by android/tools/generate.mjs from ${source}. Do not edit.\n`;

const kotlinString = (value) =>
  `"${value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\$/g, "\\$")
    .replace(/\n/g, "\\n")}"`;

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

export function renderTranslations({ strings, stepWords, langs }) {
  const keys = Object.keys(strings.en);
  const codes = langs.map((l) => l.code);
  const constant = (code) => code.toUpperCase();

  const fields = keys.map((k) => `    val ${k}: String,`).join("\n");

  const enumEntries = langs
    .map(
      (l) =>
        `    ${constant(l.code)}("${l.code}", ${kotlinString(l.label)}, ${kotlinString(l.endonym)}),`,
    )
    .join("\n");

  const tables = codes
    .map((code) => {
      const args = keys.map((k) => `            ${k} = ${kotlinString(strings[code][k])},`).join("\n");
      return `        Lang.${constant(code)} to Strings(\n${args}\n        ),`;
    })
    .join("\n");

  const words = codes
    .map((code) => {
      const entries = Object.entries(stepWords[code] ?? {})
        .map(([kind, word]) => `${kotlinString(kind)} to ${kotlinString(word)}`)
        .join(", ");
      return `        Lang.${constant(code)} to mapOf(${entries}),`;
    })
    .join("\n");

  return `${HEADER("frontend/packages/i18n/src/i18n.ts")}package org.ekyatra.saathi.i18n

/** The family app's own words. Chrome only: nothing the system *says* is here. */
data class Strings(
${fields}
)

enum class Lang(val code: String, val label: String, val endonym: String) {
${enumEntries}
    ;

    companion object {
        fun of(code: String?): Lang = entries.firstOrNull { it.code == code } ?: EN
    }
}

object Translations {
    private val strings: Map<Lang, Strings> = mapOf(
${tables}
    )

    /** The names of the care steps, per language. Empty for English, which falls back to the API's own words. */
    val stepWords: Map<Lang, Map<String, String>> = mapOf(
${words}
    )

    fun of(lang: Lang): Strings = strings.getValue(lang)
}
`;
}

const hex = (n) => n.toString(16).toUpperCase().padStart(2, "0");

/** "#1c7a33" or "rgba(r, g, b, a)" -> "0xAARRGGBB". */
export function argb(value) {
  const rgba = value.match(/^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)$/);
  if (rgba) {
    const alpha = Math.round(parseFloat(rgba[4] ?? "1") * 255);
    return `0x${hex(alpha)}${hex(+rgba[1])}${hex(+rgba[2])}${hex(+rgba[3])}`;
  }
  const short = value.match(/^#([0-9a-f]{3})$/i);
  if (short) {
    const [r, g, b] = short[1].split("").map((c) => c + c);
    return `0xFF${r}${g}${b}`.toUpperCase().replace("0XFF", "0xFF");
  }
  const long = value.match(/^#([0-9a-f]{6})$/i);
  if (long) return `0xFF${long[1].toUpperCase()}`;
  throw new Error(`unsupported colour: ${value}`);
}

export function renderTokens(tokens) {
  const colors = Object.entries(tokens.color)
    .map(([name, value]) => `    val ${camel(name)} = Color(${argb(value)})`)
    .join("\n");
  const radii = Object.entries(tokens.radius)
    .map(([name, value]) => `    val radius${name[0].toUpperCase()}${name.slice(1)} = ${value}.dp`)
    .join("\n");

  return `${HEADER("frontend/packages/theme/src/tokens.json")}package org.ekyatra.saathi.ui.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp

/** Design tokens, shared with the web apps. Status colour never carries meaning alone. */
object Tokens {
${colors}

${radii}
}
`;
}
